"""Build gettext catalogs and the widget's strict Russian/English UI catalog."""
import gettext
import json
from pathlib import Path
import subprocess


def compile_translations(root: Path):
    catalogs = {}
    for po in sorted((root / "translations").glob("*.po")):
        target = root / "package/contents/locale" / po.stem / "LC_MESSAGES/plasma_applet_org.kcromecast.widget.mo"
        target.parent.mkdir(parents=True, exist_ok=True)
        subprocess.run(["msgfmt", "--check", str(po), "-o", str(target)], check=True)
        with target.open("rb") as stream:
            catalog = gettext.GNUTranslations(stream)._catalog
        catalogs[po.stem] = {key: value for key, value in catalog.items() if isinstance(key, str) and key}
    if set(catalogs) != {"en", "ru"} or catalogs["en"].keys() != catalogs["ru"].keys():
        raise ValueError("English and Russian catalogs must contain the same messages")
    for key, value in catalogs["en"].items():
        if value != key or not catalogs["ru"][key]:
            raise ValueError("Missing translation: " + key)
    target = root / "package/contents/ui/Translations.js"
    target.write_text(".pragma library\n// Generated by scripts/translations.py; edit translations/*.po.\n"
                      + "var catalogs = " + json.dumps(catalogs, ensure_ascii=False, indent=4) + ";\n")


if __name__ == "__main__":
    compile_translations(Path(__file__).resolve().parents[1])
